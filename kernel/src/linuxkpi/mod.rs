/// Converts a Linux-style status (0 or a negative error number) into a
/// `Result` with a description.
fn status_to_result(status: c_int) -> Result<(), &'static str> {
    match -status {
        0 => Ok(()),
        ENOMEM => Err("out of memory"),
        EBUSY => Err("device busy"),
        ENODEV => Err("no such device"),
        EINVAL => Err("invalid argument"),
        _ => Err("driver reported an error"),
    }
}
