//! LinuxKPI: the Linux kernel programming interface, implemented on Omit OS.
//!
//! Unmodified Linux drivers (in `drivers/linux/`) are compiled against the
//! headers in `compat/linux-kpi/include/` and linked into the kernel. The
//! functions those headers declare are defined here, as `extern "C"`
//! symbols, in terms of native kernel facilities: PCI configuration access,
//! device memory mapping, the heap and the log.
//!
//! This is not Linux and does not make Linux drivers work in general. Each
//! driver needs exactly the interfaces it uses to be provided, with the
//! semantics it expects, and is only claimed to work where it has been
//! tested (see `drivers/linux/README.md`).
//!
//! # Safety model
//!
//! The C drivers are trusted kernel code. The functions below are called by
//! them with pointers to structures whose layout is fixed by the headers
//! and mirrored in this module; [`init`] verifies at start-up that both
//! sides agree on that layout before any driver runs.

