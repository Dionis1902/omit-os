/// Shared implementation of the `pci_write_config_*` family.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module; the value
/// written is the bound driver's responsibility.
unsafe fn write_config(pdev: *const PciDev, offset: c_int, width: u8, value: u32) -> c_int {
    let Ok(offset) = u8::try_from(offset) else {
        return -EINVAL;
    };
    // SAFETY: guaranteed by the caller.
    match unsafe { native(pdev) } {
        Some(device) => {
            // SAFETY: the request comes from the driver bound to the device.
            unsafe { device.write_config(offset, width, value) };
            0
        }
        None => -ENODEV,
    }
}

