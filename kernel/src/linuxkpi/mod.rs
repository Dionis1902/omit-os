/// `address` must have come from [`pci_ioremap_bar`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn iounmap(_address: *mut c_void) {}

/// Shared implementation of the `pci_read_config_*` family.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module.
unsafe fn read_config(pdev: *const PciDev, offset: c_int, width: u8) -> Option<u32> {
    let offset = u8::try_from(offset).ok()?;
    // SAFETY: guaranteed by the caller.
    let device = unsafe { native(pdev) }?;
    let shift = 8 * u32::from(offset & 3);
    let value = device.config_u32(offset) >> shift;
    Some(match width {
        1 => value & 0xFF,
        2 => value & 0xFFFF,
        _ => value,
    })
}

/// `pci_read_config_byte`.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module and `value`
/// valid for a write.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn pci_read_config_byte(
    pdev: *const PciDev,
    offset: c_int,
    value: *mut u8,
) -> c_int {
    // SAFETY: guaranteed by the caller.
    match unsafe { read_config(pdev, offset, 1) } {
        Some(read) => {
            // SAFETY: guaranteed by the caller.
            unsafe { value.write(read as u8) };
            0
        }
        None => -ENODEV,
    }
}

