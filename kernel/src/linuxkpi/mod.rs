/// `pci_ioremap_bar`: maps a memory BAR and returns its virtual address,
/// or null.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module, and the
/// driver must not be using the device yet (the BAR is probed for its
/// size).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn pci_ioremap_bar(pdev: *mut PciDev, bar: c_int) -> *mut c_void {
    let Ok(index) = u8::try_from(bar) else {
        return core::ptr::null_mut();
    };
    // SAFETY: guaranteed by the caller.
    let Some(device) = (unsafe { native(pdev) }) else {
        return core::ptr::null_mut();
    };
    // SAFETY: called from the driver's probe, before it uses the device.
    let (Some(region), Some(size)) = (device.memory_bar(index), unsafe {
        device.memory_bar_size(index)
    }) else {
        warn!(
            "linuxkpi: {:02x}:{:02x}.{}: BAR {index} is not a usable memory region (raw {:#010x})",
            device.bus,
            device.device,
            device.function,
            device.bar_raw(index)
        );
        return core::ptr::null_mut();
    };
    paging::map_mmio(region.address, size).map_or(core::ptr::null_mut(), |virt| virt as *mut c_void)
}

/// `iounmap`. Device mappings are permanent in this kernel so far; the
/// address simply stops being used.
///
/// # Safety
///
/// `address` must have come from [`pci_ioremap_bar`].
#[unsafe(no_mangle)]
pub unsafe extern "C" fn iounmap(_address: *mut c_void) {}

/// Shared implementation of the `pci_read_config_*` family.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module.
unsafe fn read_config(pdev: *const PciDev, offset: c_int, width: u8) -> Option<u32> {
    let offset = u8::try_from(offset).ok()?;
    // SAFETY: guaranteed by the caller.
    let device = unsafe { native(pdev) }?;
    let shift = 8 * u32::from(offset & 3);
    let value = device.config_u32(offset) >> shift;
    Some(match width {
        1 => value & 0xFF,
        2 => value & 0xFFFF,
        _ => value,
    })
}

/// `pci_read_config_byte`.
///
/// # Safety
///
/// `pdev` must be a device structure created by this module and `value`
/// valid for a write.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn pci_read_config_byte(
    pdev: *const PciDev,
    offset: c_int,
    value: *mut u8,
) -> c_int {
    // SAFETY: guaranteed by the caller.
    match unsafe { read_config(pdev, offset, 1) } {
        Some(read) => {
            // SAFETY: guaranteed by the caller.
            unsafe { value.write(read as u8) };
            0
        }
        None => -ENODEV,
    }
}

